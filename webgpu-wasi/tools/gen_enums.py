#!/usr/bin/env python3
"""Generates src/enums.h: conversions between webgpu.h's enums and the
wasi:webgpu@0.0.1 WIT enums as wit-bindgen C spells them.

The two sides name the same values differently (WGPUTextureFormat_RGBA8UnormSrgb
against rgba8unorm-srgb), so they are paired by name with case, dashes and
underscores ignored, and WIT's leading `d` on dimensions (d2-array) moved to
where webgpu.h has it (2DArray). A webgpu.h value with no WIT counterpart
converts to `false`; a WIT value with no webgpu.h counterpart to the enum's
Undefined (or 0).

Run from webgpu-wasi/: python tools/gen_enums.py
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
WIT = HERE / "wit/deps/webgpu/webgpu.wit"
HEADER = HERE / "include/webgpu/webgpu.h"
OUT = HERE / "src/enums.h"

# WIT enum -> webgpu.h enum
PAIRS = [
    ("gpu-power-preference", "WGPUPowerPreference"),
    ("gpu-feature-name", "WGPUFeatureName"),
    ("gpu-texture-format", "WGPUTextureFormat"),
    ("gpu-texture-dimension", "WGPUTextureDimension"),
    ("gpu-texture-view-dimension", "WGPUTextureViewDimension"),
    ("gpu-texture-aspect", "WGPUTextureAspect"),
    ("gpu-address-mode", "WGPUAddressMode"),
    ("gpu-filter-mode", "WGPUFilterMode"),
    ("gpu-mipmap-filter-mode", "WGPUMipmapFilterMode"),
    ("gpu-compare-function", "WGPUCompareFunction"),
    ("gpu-buffer-binding-type", "WGPUBufferBindingType"),
    ("gpu-sampler-binding-type", "WGPUSamplerBindingType"),
    ("gpu-texture-sample-type", "WGPUTextureSampleType"),
    ("gpu-storage-texture-access", "WGPUStorageTextureAccess"),
    ("gpu-query-type", "WGPUQueryType"),
    ("gpu-error-filter", "WGPUErrorFilter"),
    ("gpu-buffer-map-state", "WGPUBufferMapState"),
]


def wit_enums(text):
    enums = {}
    for m in re.finditer(r"^\s*enum ([a-z0-9-]+) \{([^}]*)\}", text, re.M):
        cases = [c.strip() for c in m.group(2).split(",") if c.strip()]
        enums[m.group(1)] = cases
    return enums


def header_enums(text):
    enums = {}
    for m in re.finditer(r"typedef enum (WGPU\w+) \{([^}]*)\}", text):
        cases = re.findall(r"(%s_\w+) = (0x[0-9A-Fa-f]+)" % m.group(1), m.group(2))
        enums[m.group(1)] = [c for c, _ in cases if not c.endswith("_Force32")]
    return enums


def norm_wit(case):
    m = re.match(r"d(\d)(.*)", case)
    if m:
        case = m.group(1) + "d" + m.group(2)
    return case.replace("-", "").lower()


def norm_header(case, enum):
    return case[len(enum) + 1:].replace("_", "").lower()


def c_name(s):
    return re.sub(r"[^A-Za-z0-9]", "_", s)


def main():
    wit = wit_enums(WIT.read_text())
    hdr = header_enums(HEADER.read_text())
    out = [
        "// Generated by tools/gen_enums.py from wit/deps/webgpu/webgpu.wit and",
        "// include/webgpu/webgpu.h. Do not edit.",
        "#ifndef WEBGPU_WASI_ENUMS_H_",
        "#define WEBGPU_WASI_ENUMS_H_",
        "",
        "#include <stdbool.h>",
        '#include "webgpu/webgpu.h"',
        '#include "webgpu_wasi.h"',
        "",
    ]
    for wit_name, enum in PAIRS:
        cases = wit[wit_name]
        by_norm = {norm_header(c, enum): c for c in hdr[enum]}
        wtype = "wasi_webgpu_webgpu_%s_t" % c_name(wit_name)
        macro = "WASI_WEBGPU_WEBGPU_%s_" % c_name(wit_name).upper()
        fn = c_name(wit_name[4:])
        pairs = []
        for case in cases:
            native = by_norm.get(norm_wit(case))
            if native is None:
                sys.exit("no %s value for %s.%s" % (enum, wit_name, case))
            pairs.append((macro + c_name(case).upper(), native))
        out.append("static inline bool wgpu_wasi_%s_to_wasi(%s value, %s* out) {" % (fn, enum, wtype))
        out.append("    switch (value) {")
        for w, n in pairs:
            out.append("    case %s: *out = %s; return true;" % (n, w))
        out.append("    default: return false;")
        out.append("    }")
        out.append("}")
        undefined = enum + "_Undefined"
        fallback = undefined if undefined in hdr[enum] else "(%s)0" % enum
        out.append("static inline %s wgpu_wasi_%s_from_wasi(%s value) {" % (enum, fn, wtype))
        out.append("    switch (value) {")
        for w, n in pairs:
            out.append("    case %s: return %s;" % (w, n))
        out.append("    default: return %s;" % fallback)
        out.append("    }")
        out.append("}")
        out.append("")
    # Feature names as the strings gpu-supported-features.has takes: the WIT
    # enum's own spellings, plus the standard names it predates.
    extra = {
        "WGPUFeatureName_CoreFeaturesAndLimits": "core-features-and-limits",
        "WGPUFeatureName_TextureFormatsTier1": "texture-formats-tier1",
        "WGPUFeatureName_TextureFormatsTier2": "texture-formats-tier2",
        "WGPUFeatureName_PrimitiveIndex": "primitive-index",
        "WGPUFeatureName_TextureComponentSwizzle": "texture-component-swizzle",
        "WGPUFeatureName_SubgroupSizeControl": "subgroup-size-control",
    }
    by_norm = {norm_header(c, "WGPUFeatureName"): c for c in hdr["WGPUFeatureName"]}
    names = [(by_norm[norm_wit(c)], c) for c in wit["gpu-feature-name"]] + sorted(extra.items())
    out.append("// Every feature webgpu.h names that has a WebGPU spelling, for has() and")
    out.append("// for listing a supported set.")
    out.append("static const struct { WGPUFeatureName feature; const char* name; } wgpu_wasi_feature_names[] = {")
    for n, s in names:
        out.append('    { %s, "%s" },' % (n, s))
    out.append("};")
    out.append("")
    out.append("#endif")
    with OUT.open("w", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
